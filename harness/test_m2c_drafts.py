"""Drafts must come from verified assembly and stay in the project's build storage."""

import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import m2c_drafts as drafts


class DraftTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        config = self.root / "config/TEST01/symbols.txt"
        config.parent.mkdir(parents=True)
        config.write_text(
            "fn_80001000 = .text:0x80001000; // type:function size:0x8\n"
            "fn_80001008 = .text:0x80001008; // type:function size:0x8\n"
            "fn_80001010 = .text:0x80001010; // type:function size:0xC\n")
        (self.root / "config/TEST01/build.sha1").write_text("a" * 40 + "  main.dol\n")
        build_config = self.root / "build/TEST01/config.json"
        build_config.parent.mkdir(parents=True)
        build_config.write_text(json.dumps({"units": [{"name": "auto_text", "autogenerated": True,
                                                       "code_size": 28}]}))
        assembly = self.root / "build/TEST01/asm/auto_text.s"
        assembly.parent.mkdir(parents=True)
        assembly.write_text(
            ".text\n.fn fn_80001000, global\n"
            "/* 80001000 00000000  60 00 00 00 */ nop\n"
            "/* 80001004 00000004  4E 80 00 20 */ blr\n.endfn fn_80001000\n"
            ".fn fn_80001008, global\n"
            "/* 80001008 00000008  60 00 00 00 */ nop\n"
            "/* 8000100C 0000000C  4E 80 00 20 */ blr\n.endfn fn_80001008\n"
            ".fn fn_80001010, global\n"
            "/* 80001010 00000010  4E 80 00 20 */ blr\n.endfn fn_80001010\n")

    def test_capture_requires_symbol_size_and_exact_addresses(self):
        rows = drafts.candidates(self.root, "TEST01", 4, 12)
        self.assertEqual([row["symbol"] for row in rows], ["fn_80001000", "fn_80001008"])
        self.assertEqual([row["size"] for row in rows], [8, 8])
        self.assertTrue(rows[0]["assembly"].startswith(b".text\n.balign 4\n.fn"))
        self.assertEqual(len(drafts.spread(rows, 1)), 1)

    def test_runtime_project_tools_override_the_configured_checkout(self):
        project_tools = self.root / "tools"
        (project_tools / "decomp_work").mkdir(parents=True)
        configured_tools = str(self.root / "configured-tools")
        with patch.object(sys, "path", [configured_tools]):
            drafts.bind_project_tools(self.root, prefer=True)
            self.assertEqual(sys.path, [str(project_tools.resolve()), configured_tools])

    def test_orphaned_assembly_is_not_redrafted_after_split(self):
        orphan = self.root / "build/TEST01/asm/auto_old_text.s"
        orphan.write_text(".text\n.fn fn_80001000, global\n"
                          "/* 80001000 00000000  60 00 00 00 */ nop\n"
                          "/* 80001004 00000004  4E 80 00 20 */ blr\n.endfn fn_80001000\n")
        rows = drafts.candidates(self.root, "TEST01", 8, 8)
        self.assertEqual(len(rows), 2)
        self.assertTrue(all(row["unit"] == "auto_text" for row in rows))

    def test_nested_cpp_units_do_not_require_autogenerated_marker(self):
        config = self.root / "build/TEST01/config.json"
        config.write_text(json.dumps({"units": [{"name": "game/auto_text.cpp", "autogenerated": False,
                                                  "code_size": 28}]}))
        assembly = self.root / "build/TEST01/asm/auto_text.s"
        nested = self.root / "build/TEST01/asm/game/auto_text.s"
        nested.parent.mkdir(parents=True)
        assembly.rename(nested)

        rows = drafts.candidates(self.root, "TEST01", 8, 8)

        self.assertEqual(len(rows), 2)
        self.assertTrue(all(row["unit"] == "game/auto_text" for row in rows))

    def test_source_backed_exact_functions_are_not_redrafted(self):
        with patch.object(drafts.m2c_context, "_report_exact_rows",
                          return_value=[{"symbol": "fn_80001000"}]):
            rows = drafts.candidates(self.root, "TEST01", 8, 8)

        self.assertEqual([row["symbol"] for row in rows], ["fn_80001008"])

    def test_holdout_selects_only_exact_functions(self):
        with patch.object(drafts.m2c_context, "_report_exact_rows",
                          return_value=[{"symbol": "fn_80001000"}]):
            rows = drafts.candidates(self.root, "TEST01", 8, 8, matched=True)

        self.assertEqual([row["symbol"] for row in rows], ["fn_80001000"])

    def test_address_range_limits_targeted_sweep(self):
        translated = {"status": "ok", "draft": "void f(void) {}", "context_mode": "assembly_only",
                      "diagnostics": {}, "artifacts": "ignored/draft"}
        with patch.object(drafts, "build_check", return_value={"status": "exact", "expected": "a" * 40}), \
             patch.object(drafts.decompile, "tool_metadata", return_value={"revision": "test", "fingerprint": "hash"}), \
             patch.object(drafts.decompile, "translate", return_value=translated), \
             patch.object(drafts.m2c_report, "refresh_report"):
            result = drafts.run(self.root, "TEST01", 0, 1, 5, 4, 12, start=0x80001008, end=0x80001010)
        self.assertEqual(result["total"], 1)

    def test_replay_uses_frozen_bytes_and_rechecks_symbol_boundaries(self):
        batch = self.root / "frozen"
        (batch / "input").mkdir(parents=True)
        assembly = (".text\n.fn fn_80001000, global\n"
                    "/* 80001000 00000000  60 00 00 00 */ nop\n"
                    "/* 80001004 00000004  4E 80 00 20 */ blr\n.endfn fn_80001000\n").encode()
        digest = drafts.sha256(assembly)
        (batch / "input/one.s").write_bytes(assembly)
        (batch / "targets.json").write_text(json.dumps({"identity": {"version": "TEST01",
            "dol_sha1": "a" * 40}, "targets": [{"id": "one", "symbol": "fn_80001000",
            "address": 0x80001000, "size": 8, "unit": "auto_text",
            "assembly_sha256": digest}]}))
        rows = drafts.replay_rows(self.root, "TEST01", batch)
        self.assertEqual(rows[0]["assembly"], assembly)
        self.assertEqual(rows[0]["unit"], "auto_text")
        data = json.loads((batch / "targets.json").read_text())
        data["targets"][0]["size"] = 12
        (batch / "targets.json").write_text(json.dumps(data))
        with self.assertRaisesRegex(ValueError, "boundary changed"):
            drafts.replay_rows(self.root, "TEST01", batch)

    def test_run_is_resumable_and_project_local(self):
        translated = {"status": "ok", "draft": "void f(void) {}", "context_mode": "assembly_only",
                      "diagnostics": {"unknown_fields": 0}, "artifacts": "ignored/draft"}
        with patch.object(drafts, "build_check", return_value={"status": "exact", "expected": "a" * 40}), \
             patch.object(drafts.decompile, "tool_metadata", return_value={"revision": "test", "fingerprint": "hash"}), \
             patch.object(drafts.decompile, "translate", return_value=translated) as translate, \
             patch.object(drafts.m2c_report, "refresh_report") as refresh:
            first = drafts.run(self.root, "TEST01", 2, 1, 5, 4, 12)
            second = drafts.run(self.root, "TEST01", 2, 1, 5, 4, 12)
        self.assertEqual(first["run_id"], second["run_id"])
        self.assertEqual(first["counts"], {"ok": 2})
        self.assertEqual(translate.call_count, 2)
        self.assertEqual(translate.call_args.kwargs["version"], "TEST01")
        self.assertEqual(refresh.call_count, 2)
        folder = Path(first["folder"])
        self.assertEqual(len(list((folder / "input").glob("*.s"))), 2)
        results = json.loads((folder / "results.json").read_text())
        self.assertEqual([row["source"] for row in results["results"]], [None, None])
        self.assertTrue(all(row["auto_generated"] for row in results["results"]))
        self.assertTrue(folder.is_relative_to((self.root / "build/decomp-support/TEST01").resolve()))

    def test_mismatched_dol_is_rejected(self):
        with patch.object(drafts, "build_check", return_value={"status": "mismatch"}):
            with self.assertRaisesRegex(ValueError, "byte-exact DOL"):
                drafts.run(self.root, "TEST01", 2, 1, 5, 4, 12)


if __name__ == "__main__":
    unittest.main()
